// Compile contracts/QDayRegistry.sol with solc 0.8.24 (optimizer on, 200 runs, via-IR, EVM version paris)
// and write contracts/QDayRegistry.artifact.ts in the same shape as the template's Counter artifact.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import solc from "solc";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "..", "contracts");
const name = "QDayRegistry";
const input = {
  language: "Solidity",
  sources: { [`${name}.sol`]: { content: readFileSync(join(dir, `${name}.sol`), "utf8") } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "paris",
    viaIR: true,
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } },
  },
};
const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (out.errors ?? []).filter((e) => e.severity === "error");
for (const e of out.errors ?? []) console.error(e.formattedMessage);
if (errors.length) process.exit(1);
const c = out.contracts[`${name}.sol`][name];
const ts = `/**
 * Compiled artifact for \`contracts/${name}.sol\`.
 *
 * Generated by \`npm run compile\` (scripts/compile.mjs): solc ${solc.version()}, optimizer 200 runs, via-IR, EVM paris.
 * Do not edit by hand.
 */
import type { Hex } from "viem";

export const qdayRegistryAbi = ${JSON.stringify(c.abi, null, 2)} as const;

export const qdayRegistryBytecode: Hex = "0x${c.evm.bytecode.object}";

export const qdayRegistryDeployedBytecode: Hex = "0x${c.evm.deployedBytecode.object}";
`;
writeFileSync(join(dir, `${name}.artifact.ts`), ts);
console.log(`${name}: ${c.evm.bytecode.object.length / 2} bytes creation code, ${c.evm.deployedBytecode.object.length / 2} bytes runtime (solc ${solc.version()})`);
